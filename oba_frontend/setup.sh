#!/bin/bash

echo "=========================================================="
echo "        🚀 한입기사 React Native 환경 자동 설정"
echo "=========================================================="

# ----------------------------------------------------------------------
# helper function: runs a command + stops script on error
# ----------------------------------------------------------------------
run() {
    echo "→ $1"
    eval "$1"
    if [ $? -ne 0 ]; then
        echo "❌ 오류 발생: $1"
        echo "스크립트를 중단합니다. 문제 해결 후 다시 실행해주세요."
        exit 1
    fi
}

# ----------------------------------------------------------------------
# 1. Node.js 확인
# ----------------------------------------------------------------------
echo "[1/5] 🔍 Node.js 버전 확인 중..."
if ! command -v node &> /dev/null; then
    echo "❌ Node.js가 설치되어 있지 않습니다."
    echo "👉 Node.js 18+ 버전을 설치 후 다시 실행하세요."
    exit 1
fi

NODE_VERSION=$(node -v)
echo "   ➜ Node 버전: $NODE_VERSION"


# ----------------------------------------------------------------------
# 2. expo-cli 전역 설치
# ----------------------------------------------------------------------
echo "[2/5] 📦 expo-cli 설치 중..."
run "npm install -g expo-cli"

echo "   ➜ expo 버전 확인..."
run "expo --version"


# ----------------------------------------------------------------------
# 3. 프로젝트 의존성 설치
# ----------------------------------------------------------------------
echo "[3/5] 📦 프로젝트 패키지 설치 중..."
run "npm install"


# ----------------------------------------------------------------------
# 4. expo-blur 설치 (필수)
# ----------------------------------------------------------------------
echo "[4/5] ✨ expo-blur 설치 중..."
run "npx expo install expo-blur"


# ----------------------------------------------------------------------
# 5. Expo 실행
# ----------------------------------------------------------------------
echo "[5/5] 🏁 Expo 프로젝트 실행!"
run "npx expo start"

echo "=========================================================="
echo "     ✅ 모든 과정이 정상적으로 완료되었습니다!"
echo "=========================================================="
